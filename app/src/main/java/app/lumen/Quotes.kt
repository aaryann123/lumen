/** Indexes to pick from: "all", "heroes" or "villains". */
fun pool(show: String) = QUOTES.indices.filter { show == "all" || QUOTES[it].villain == (show == "villains") }
    .ifEmpty { QUOTES.indices.toList() } // e.g. "heroes" with an all-villain list: show everything

/**
 * Shuffle-bag pick: the next index from [bag] (still-unseen quotes), refilled with a fresh shuffle of [pool] once
 * empty, so every quote shows once per round and [last] never shows twice in a row. Returns the pick and the new bag.
 */
fun deal(bag: List<Int>, pool: List<Int>, last: Int, random: Random = Random): Pair<Int, List<Int>> {
    val left = bag.filter { it in pool }
    val deck = left.ifEmpty { pool.shuffled(random).let { if (it.size > 1 && it[0] == last) it.drop(1) + it[0] else it } }
    return deck[0] to deck.drop(1)
}

/**
 * The quote to show in a slot that fits [maxChars]: [current] if it's short enough, else a stand-in short one.
 * Samsung's lock screen forces its own big text and ~2 lines, so long lines would end mid-sentence there.
 */
fun fitting(current: Int, maxChars: Int): Int {
    if (QUOTES[current].line.length <= maxChars) return current
    val short = QUOTES.indices.filter { QUOTES[it].line.length <= maxChars }.ifEmpty { return QUOTES.indices.minBy { QUOTES[it].line.length } }
    return short[current % short.size]
}
